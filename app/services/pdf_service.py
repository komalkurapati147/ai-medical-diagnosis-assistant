"""
Generates a downloadable PDF medical report combining the model's
prediction, the SHAP-based explanation table, and the LLM narrative.
Uses reportlab (pure-Python, no external binary dependency like
wkhtmltopdf, which keeps the Docker image small).
"""
import os
from datetime import datetime
from typing import List, Dict

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import cm
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
)

from app.config import settings


def generate_pdf_report(
    report_id: str,
    patient_name: str,
    symptoms: Dict[str, int],
    predicted_disease: str,
    confidence_score: float,
    top_symptoms: List[Dict],
    llm_summary: str,
) -> str:
    filename = f"{report_id}.pdf"
    filepath = os.path.join(settings.reports_dir, filename)

    doc = SimpleDocTemplate(filepath, pagesize=A4, topMargin=2 * cm, bottomMargin=2 * cm)
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle("TitleStyle", parent=styles["Title"], textColor=colors.HexColor("#1f3a5f"))
    heading_style = ParagraphStyle("Heading", parent=styles["Heading2"], textColor=colors.HexColor("#1f3a5f"))

    elements = []
    elements.append(Paragraph("AI Medical Diagnosis Assistant", title_style))
    elements.append(Paragraph("Preliminary AI-Generated Health Report", styles["Normal"]))
    elements.append(Spacer(1, 12))

    meta_table = Table([
        ["Report ID", report_id],
        ["Patient", patient_name or "Anonymous"],
        ["Generated on", datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC")],
    ], colWidths=[4 * cm, 10 * cm])
    meta_table.setStyle(TableStyle([
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("TEXTCOLOR", (0, 0), (0, -1), colors.grey),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]))
    elements.append(meta_table)
    elements.append(Spacer(1, 16))

    elements.append(Paragraph("Reported Symptoms", heading_style))
    present = [s.replace("_", " ").title() for s, v in symptoms.items() if v == 1]
    elements.append(Paragraph(", ".join(present) if present else "None reported", styles["Normal"]))
    elements.append(Spacer(1, 12))

    elements.append(Paragraph("Model Prediction", heading_style))
    pred_table = Table([
        ["Predicted Condition", predicted_disease],
        ["Confidence Score", f"{confidence_score:.1%}"],
    ], colWidths=[5 * cm, 9 * cm])
    pred_table.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.5, colors.lightgrey),
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#eef3fa")),
        ("FONTSIZE", (0, 0), (-1, -1), 10),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
    ]))
    elements.append(pred_table)
    elements.append(Spacer(1, 12))

    elements.append(Paragraph("Explainability (Top Contributing Symptoms — SHAP)", heading_style))
    shap_rows = [["Symptom", "Present?", "Impact on Prediction"]]
    for s in top_symptoms:
        shap_rows.append([
            s["feature"].replace("_", " ").title(),
            "Yes" if s["value"] == 1 else "No",
            f"{s['impact']:+.3f}",
        ])
    shap_table = Table(shap_rows, colWidths=[6 * cm, 3 * cm, 5 * cm])
    shap_table.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.5, colors.lightgrey),
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1f3a5f")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
    ]))
    elements.append(shap_table)
    elements.append(Spacer(1, 12))

    elements.append(Paragraph("AI-Generated Explanation", heading_style))
    elements.append(Paragraph(llm_summary, styles["Normal"]))
    elements.append(Spacer(1, 16))

    disclaimer = (
        "Disclaimer: This report is generated by an automated machine-learning "
        "system for informational purposes only. It is NOT a substitute for "
        "professional medical advice, diagnosis, or treatment. Always consult a "
        "qualified healthcare provider."
    )
    elements.append(Paragraph(disclaimer, ParagraphStyle(
        "Disclaimer", parent=styles["Italic"], textColor=colors.red, fontSize=8
    )))

    doc.build(elements)
    return filepath
